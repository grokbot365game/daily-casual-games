var shapeIds = {};
var sweeps = {};
var colHits = { lo: 0, hi: 0 };
var seen = {};
var badRoll = 0;
var s;
for (s = 1; s <= 40; s++) {
  var roll = L.rollRound(L.ROUNDS[3], L.mulberry32(s * 7919), s % 2 === 0 ? "neko" : null);
  shapeIds[roll.shapeId] = true;
  sweeps[roll.sweep.toFixed(2)] = true;
  if (roll.cols === L.ROUNDS[3].cols[0]) colHits.lo++;
  if (roll.cols === L.ROUNDS[3].cols[1]) colHits.hi++;
  if (roll.sweep < L.ROUNDS[3].sweep[0] - 1e-9 || roll.sweep > L.ROUNDS[3].sweep[1] + 1e-9) badRoll++;
  if (roll.mirror) badRoll++;
  var key = roll.shown.map(function (n) { return n.toFixed(3); }).join(",");
  seen[key] = true;
  roll.targets.forEach(function (t) {
    if (!L.reachable(t, roll.sweep)) badRoll++;
  });
  if (L.mirrorGap(roll.shown) < 0.24) badRoll++;
  var idlePct = L.accuracyPercent(roll.targets, roll.targets.map(function () { return 1; }));
  if (idlePct >= roll.pass) badRoll++;
}
